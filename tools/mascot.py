#!/usr/bin/env python3
"""chatbit mascot: the kitten with a headset, drawn on a 24x21 pixel grid.

Writes, from the single GRID below:
  app drawables  chatbit_cat (fixed colours), chatbit_bow (headset, tinted with the accent colour
                 by ChatbitLogo), chatbit_bow_knot (headset shading), ic_launcher_foreground,
                 ic_launcher_monochrome, ic_notification (status bar), and the launcher PNGs of
                 every density;
  store icon     fastlane/metadata/android/*/images/icon.png (512 px);
  site images    when a site folder is given: img/kitty.webp, favicon.ico, favicon-32.png,
                 icon-192.png, apple-touch-icon.png.

The grid keeps the old cat's layout (eyes on rows 11-13, columns 6-7 and 16-17) so the outfits
drawn by ChatbitLogo still fit. Usage: python3 tools/mascot.py [path/to/site]
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw

GRID = [
    "...K................K...",
    "...KK..............KK...",
    "...KPK..BBBBBBBB..KPK...",
    "...KPPBB........BBPPK...",
    "...KWPPKKKKKKKKKKPPWK...",
    "...KWWWWWGWGWGWWWWWWK...",
    "....KWWWWGWGWGWWWWWK....",
    "....KWWWWWWWWWWWWWWK....",
    "...KWWWWWWWWWWWWWWWWK...",
    "..KWWWWWWWWWWWWWWWWWWK..",
    ".BBWWKWWWWWWWWWWWWKWWBB.",
    "bBBWWWKKWWWWWWWWKKWWWBBb",
    "bBBGWWKKWWWWWWWWKKWWGBBb",
    "bBBGWWKKWWWWWWWWKKWWGBBb",
    ".BBWPPWWWWWNNWWWWWPPWBB.",
    "..MWWWWWbWKWWKWWWWWWWK..",
    "..KMMMMMbWWKKWWWWWWWWK..",
    "...KWWWWWWWWWWWWWWWWK...",
    "....KKWWWWWWWWWWWWKK....",
    "......KKKWWWWWWKKK......",
    ".........KKKKKK.........",
]
# K outline, W fur, G grey tabby marks, P pink (inner ears, blush), N nose, M microphone boom,
# B headset (accent colour in the app), b headset shade and microphone head
FIXED = {"K": "#1A1A1A", "W": "#FFFFFF", "G": "#CDCDD2", "P": "#FFAAC8", "N": "#FF69A0", "M": "#3C3C3C"}
PINK, PINK_DARK, ICON_BG = "#E83C78", "#A8144F", "#FFD6E7"
W, H = 24, 21

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "app/src/main/res"


def cells(chars):
    return [(x, y) for y, row in enumerate(GRID) for x, c in enumerate(row) if c in chars]


def path(points, scale=1.0, dx=0.0, dy=0.0):
    def n(v):
        return f"{v:g}"
    s = scale
    return "".join(f"M{n(dx + x * s)},{n(dy + y * s)}h{n(s)}v{n(s)}h-{n(s)}z" for x, y in points)


def vector(comment, size, viewport, layers):
    w, h = size
    vw, vh = viewport
    body = "".join(
        f'    <path\n        android:fillColor="{color}"\n        android:pathData="{d}" />\n'
        for color, d in layers if d
    )
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- {comment} (generated by tools/mascot.py) -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{w}dp"\n    android:height="{h}dp"\n'
        f'    android:viewportWidth="{vw}"\n    android:viewportHeight="{vh}">\n'
        f"{body}</vector>\n"
    )


def colour_of(c):
    return FIXED.get(c) or {"B": PINK, "b": PINK_DARK}.get(c)


def render(scale, bg=None, size=None, radius=0):
    """The mascot as an image; centred on a rounded square of the icon pink when size is given."""
    cat = Image.new("RGBA", (W * scale, H * scale), (0, 0, 0, 0))
    d = ImageDraw.Draw(cat)
    for y, row in enumerate(GRID):
        for x, c in enumerate(row):
            col = colour_of(c)
            if col:
                d.rectangle([x * scale, y * scale, (x + 1) * scale - 1, (y + 1) * scale - 1], fill=col)
    if size is None:
        return cat
    out = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    if bg:
        ImageDraw.Draw(out).rounded_rectangle([0, 0, size - 1, size - 1], radius=radius, fill=bg)
    out.paste(cat, ((size - cat.width) // 2, (size - cat.height) // 2 + scale // 2), cat)
    return out


def main():
    drawable = RES / "drawable"
    fixed_layers = [(col, path(cells(c))) for c, col in FIXED.items()]
    (drawable / "chatbit_cat.xml").write_text(vector(
        "chatbit in-app logo: the kitten without its headset (the headset is a tinted layer)",
        (96, 84), (W, H), fixed_layers))
    (drawable / "chatbit_bow.xml").write_text(vector(
        "chatbit headset, tinted with the accent colour", (96, 84), (W, H), [("#FFFFFF", path(cells("Bb")))]))
    (drawable / "chatbit_bow_knot.xml").write_text(vector(
        "chatbit headset shading: darkens the tinted headset", (96, 84), (W, H), [("#59000000", path(cells("b")))]))

    # adaptive icon: 108 dp, the grid scaled by 2.5 and centred in the 72 dp safe zone
    s, dx, dy = 2.5, 24.0, 24.0 + (24 - H) * 2.5 / 2
    fore = [(col, path(cells(c), s, dx, dy)) for c, col in FIXED.items()]
    fore += [(PINK, path(cells("B"), s, dx, dy)), (PINK_DARK, path(cells("b"), s, dx, dy))]
    (drawable / "ic_launcher_foreground.xml").write_text(vector(
        "chatbit: 24x21 pixel-art kitten with a headset", (108, 108), (108, 108), fore))
    (drawable / "ic_launcher_monochrome.xml").write_text(vector(
        "chatbit: monochrome silhouette for themed icons", (108, 108), (108, 108),
        [("#000000", path(cells("KWGPNMBb"), s, dx, dy))]))

    # status bar: white silhouette, the eyes and mouth left as holes so the face still reads
    face = {(x, y) for x, y in cells("K") if 5 <= x <= 18 and 10 <= y <= 16}
    shape = [p for p in cells("KWGPNMBb") if p not in face]
    (drawable / "ic_notification.xml").write_text(vector(
        "chatbit status bar icon: the kitten silhouette", (24, 24), (24, 24),
        [("#FFFFFF", path(shape, 1, 0, 1.5))]))

    # launcher PNGs for older launchers: legacy icon, adaptive foreground and background
    for folder, legacy, adaptive in [("mdpi", 48, 108), ("hdpi", 72, 162), ("xhdpi", 96, 216),
                                     ("xxhdpi", 144, 324), ("xxxhdpi", 192, 432)]:
        out = RES / f"mipmap-{folder}"
        render(max(1, legacy // 30), ICON_BG, legacy, legacy // 5).save(out / "ic_launcher.png")
        fg = Image.new("RGBA", (adaptive, adaptive), (0, 0, 0, 0))
        cat = render(adaptive * 60 // 108 // W)
        fg.paste(cat, ((adaptive - cat.width) // 2, (adaptive - cat.height) // 2), cat)
        fg.save(out / "ic_launcher_adaptive_fore.png")
        Image.new("RGBA", (adaptive, adaptive), ICON_BG).save(out / "ic_launcher_adaptive_back.png")

    for store in (ROOT / "fastlane/metadata/android").glob("*/images"):
        render(16, ICON_BG, 512, 96).save(store / "icon.png")

    if len(sys.argv) > 1:
        site = Path(sys.argv[1])
        render(12).save(site / "img/kitty.webp", lossless=True)
        render(7, ICON_BG, 192, 40).save(site / "icon-192.png")
        render(7, ICON_BG, 180, 38).save(site / "apple-touch-icon.png")
        render(1, None, 32).save(site / "favicon-32.png")
        render(2, None, 64).save(site / "favicon.ico", sizes=[(16, 16), (32, 32), (48, 48), (64, 64)])
    print("mascot written")


if __name__ == "__main__":
    main()
